struct ListNode
{
    int val;
    ListNode *next;
    ListNode() : val(0), next(nullptr) {}
    ListNode(int x) : val(x), next(nullptr) {}
    ListNode(int x, ListNode *next) : val(x), next(next) {}
};

struct TreeNode
{
    int val;
    TreeNode *left;
    TreeNode *right;
    TreeNode() : val(0), left(nullptr), right(nullptr) {}
    TreeNode(int x) : val(x), left(nullptr), right(nullptr) {}
    TreeNode(int x, TreeNode *left, TreeNode *right) : val(x), left(left), right(right) {}
};

class Solution
{
public:
    // 1
    int maxEnvelopes(vector<vector<int>> &e)
    {
        sort(e.begin(), e.end(), [&](const vector<int> &e1, const vector<int> &e2)
             { return e1[0] != e2[0] ? e1[0] < e2[0] : e1[1] > e2[1]; });
        int n = e.size();

        vector<int> ret;
        ret.push_back(e[0][1]);
        for (int i = 1; i < n; i++)
        {
            if (e[i][1] > ret.back())
                ret.push_back(e[i][1]);
            else
            {
                int left = 0, right = ret.size() - 1;
                while (left < right)
                {
                    int mid = left + (right - left) / 2;
                    if (e[i][1] > ret[mid])
                        left = mid + 1;
                    else
                        right = mid;
                }
                ret[left] = e[i][1];
            }
        }

        return ret.size();
    }

    // 2
    string reorganizeString(string s)
    {
        int n = s.size(), maxCount = 0;
        char maxChar = '/0';
        unordered_map<char, int> hash;

        for (char ch : s)
            if (++hash[ch] > maxCount)
            {
                maxCount = hash[ch];
                maxChar = ch;
            }

        string ret;
        ret.append(n, '.');
        int index = 0;
        for (int i = 0; i < maxCount; i++)
        {
            if (index > n - 1)
                return "";

            ret[index] = maxChar;
            index += 2;
        }

        hash.erase(maxChar);

        for (auto [a, b] : hash)
            for (int i = 0; i < b; i++)
            {
                if (index > n - 1)
                    index = 1;

                ret[index] = a;
                index += 2;
            }

        for (char ch : ret)
            if (ch == '.')
                return "";

        return ret;
    }

    // 3
    bool wordBreak(string s, vector<string> &wordDict)
    {
        unordered_set<string> hash(wordDict.begin(), wordDict.end());

        int n = s.size();
        s = " " + s;
        vector<bool> dp(n + 1);
        dp[0] = true;

        for (int i = 1; i <= n; i++)
            for (int j = i; j >= 1; j--)
            {
                if (dp[j - 1] && hash.count(s.substr(j, i - j + 1)))
                {
                    dp[i] = true;
                    break;
                }
            }

        return dp[n];
    }

    // 4
    bool canPartition(vector<int> &nums)
    {
        int n = nums.size(), sum = 0;
        for (auto num : nums)
            sum += num;

        if (sum % 2)
            return false;

        int aim = sum / 2;
        vector<vector<bool>> dp(n + 1, vector<bool>(aim + 1));
        for (int i = 0; i <= n; i++)
            dp[i][0] = true;

        for (int i = 1; i <= n; i++)
            for (int j = 0; j <= aim; j++)
            {
                dp[i][j] = dp[i - 1][j];
                if (j >= nums[i - 1])
                    dp[i][j] = dp[i][j] || dp[i - 1][j - nums[i - 1]];
            }

        return dp[n][aim];
    }

};